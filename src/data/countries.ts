// Helper to get countries sorted by active locale (ES or EN)
export function getSortedCountries(locale: 'es' | 'en'): Country[] {
  const key = locale === 'es' ? 'nameES' : 'nameEN';
  return [...countries].sort((a, b) => a[key].localeCompare(b[key], locale, { sensitivity: 'base' }));
}

export function getCountryByCode(code: string): Country | undefined {
  return countries.find((c) => c.code === code);
}

// Helper to get countries sorted numerically by dial code, with US (+1) first
export function getCountriesSortedByDialCode(): Country[] {
  return [...countries].sort((a, b) => {
    if (a.code === 'US') return -1;
    if (b.code === 'US') return 1;
    const numA = parseInt(a.dialCode.replace(/[^0-9]/g, ''), 10);
    const numB = parseInt(b.dialCode.replace(/[^0-9]/g, ''), 10);
    if (numA !== numB) return numA - numB;
    return a.code.localeCompare(b.code);
  });
}
